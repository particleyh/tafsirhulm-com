/** Strip CJK/other non-Arabic/Latin junk that models sometimes emit */
function stripForeign(s) {
  if (typeof s !== "string") return "";
  // remove CJK, Hangul, Kana, and other common foreign blocks; keep Arabic + Latin + digits + basic punctuation
  return s
    .replace(/[\u3040-\u30FF\u3400-\u4DBF\u4E00-\u9FFF\uAC00-\uD7AF\uF900-\uFAFF\uFF00-\uFFEF]/g, "")
    .replace(/\s{2,}/g, " ")
    .trim();
}

